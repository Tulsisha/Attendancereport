class EmployeeFaceProfile(models.Model):
    ENROLLMENT_STATUS_CHOICES = [
        ('NOT_REGISTERED', 'Not Registered'),
        ('PENDING', 'Registration Pending'),
        ('REGISTERED', 'Registered'),
        ('RE_ENROLLMENT_REQUIRED', 'Re-enrollment Required'),
    ]

    user = models.OneToOneField(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='face_profile')
    # 128-dimensional floating point descriptor array generated by FaceRecognitionNet
    face_descriptor = models.JSONField(
        null=True,
        blank=True,
        help_text="128-dimensional biometric descriptor embedding array."
    )
    enrollment_status = models.CharField(
        max_length=30,
        choices=ENROLLMENT_STATUS_CHOICES,
        default='NOT_REGISTERED'
    )
    is_enrolled = models.BooleanField(default=False)
    sample_count = models.IntegerField(default=0)
    enrolled_at = models.DateTimeField(null=True, blank=True)
    enrolled_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name='enrolled_employees'
    )
    anti_spoofing_passed = models.BooleanField(default=False)
    liveness_score = models.FloatField(default=0.0)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"{self.user.username} - Face Profile ({self.get_enrollment_status_display()})"

    def save(self, *args, **kwargs):
        # Keep is_enrolled synced with enrollment_status
        if self.enrollment_status == 'REGISTERED' and self.face_descriptor:
            self.is_enrolled = True
        else:
            self.is_enrolled = False
        super().save(*args, **kwargs)

    def verify_descriptor(self, candidate_descriptor, threshold=0.55):
        """
        Calculates the Euclidean distance between candidate_descriptor and stored face_descriptor.
        Face Recognition Net uses 0.5 - 0.6 as standard Euclidean distance threshold.
        Distance <= threshold means genuine match.
        """
        if self.enrollment_status != 'REGISTERED' or not self.face_descriptor or not candidate_descriptor:
            return False, 999.0

        if len(self.face_descriptor) != len(candidate_descriptor):
            return False, 999.0

        try:
            dist = math.dist(self.face_descriptor, candidate_descriptor)
            return (dist <= threshold), dist
        except Exception:
            sq_sum = sum((a - b) ** 2 for a, b in zip(self.face_descriptor, candidate_descriptor))
            dist = math.sqrt(sq_sum)
            return (dist <= threshold), dist


class FaceChallenge(models.Model):
    """
    Cryptographic single-use nonce to prevent replay attacks and token reuse.
    A challenge token is issued to the client camera session and must be consumed within 120s.
    """
    challenge_id = models.CharField(max_length=64, unique=True, db_index=True)
    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name='face_challenges')
    action = models.CharField(max_length=30, default='punch')
    created_at = models.DateTimeField(default=timezone.now)
    is_consumed = models.BooleanField(default=False)
    consumed_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ['-created_at']

    def is_valid(self):
        if self.is_consumed:
            return False
        age = (timezone.now() - self.created_at).total_seconds()
        return age <= 120.0

    @classmethod
    def create_challenge(cls, user, action='punch'):
        token = secrets.token_urlsafe(32)
        return cls.objects.create(challenge_id=token, user=user, action=action)


