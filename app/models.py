    punch_in_location = models.CharField(
        max_length=255,
        null=True,
        blank=True
    )

    punch_out_latitude = models.DecimalField(
        max_digits=10,
        decimal_places=7,
        null=True,
        blank=True
    )

    punch_out_longitude = models.DecimalField(
        max_digits=10,
        decimal_places=7,
        null=True,
        blank=True
    )

    punch_out_location = models.CharField(
        max_length=255,
        null=True,
        blank=True
    )

    verification_method = models.CharField(
        max_length=50,
        default='face_biometric',
        choices=[
            ('face_biometric', 'Face Biometric Verification'),
            ('manual_admin', 'Admin Manual Correction'),
            ('exempt_override', 'Exempt Override'),
        ]
    )
    face_verified_in = models.BooleanField(default=False)
    face_verified_out = models.BooleanField(default=False)
    confidence_score = models.FloatField(null=True, blank=True)

    is_late = models.BooleanField(default=False)
    late_minutes = models.IntegerField(default=0)
    working_hours = models.FloatField(default=0.0)
    notes = models.TextField(blank=True, default='')

    class Meta:
        unique_together = ('user', 'date')
        ordering = ['-date']
        indexes = [
            models.Index(fields=['user', 'date']),
            models.Index(fields=['date']),
        ]

    def __str__(self):
        return f"{self.user.username} - {self.date}"

    def update_calculations(self):
        """
        Recalculates working hours, late minutes, and late status.
        Office Start: 9:30 AM
        On-time: 9:30 AM to 9:35 AM (inclusive)
        Late: after 9:35 AM
        """
        if self.punch_in:
            cutoff = time(9, 35, 0)
            target = time(9, 30, 0)
            if self.punch_in > cutoff:
                self.is_late = True
                in_mins = self.punch_in.hour * 60 + self.punch_in.minute + (self.punch_in.second / 60.0)
                target_mins = target.hour * 60 + target.minute
                self.late_minutes = max(0, int(round(in_mins - target_mins)))
            else:
                self.is_late = False
                self.late_minutes = 0
        else:
            self.is_late = False
            self.late_minutes = 0

        if self.punch_in and self.punch_out:
            in_sec = self.punch_in.hour * 3600 + self.punch_in.minute * 60 + self.punch_in.second
            out_sec = self.punch_out.hour * 3600 + self.punch_out.minute * 60 + self.punch_out.second
            diff_sec = max(0, out_sec - in_sec)
            self.working_hours = round(diff_sec / 3600.0, 2)
        else:
            self.working_hours = 0.0

    def save(self, *args, **kwargs):
        self.update_calculations()
        super().save(*args, **kwargs)

    @property
    def status(self):
        """
        Returns accurate business status:
        - Holiday: if holiday or Sunday
        - Present / On Time: punch in <= 9:35 AM with punch out
        - Late: punch in > 9:35 AM with punch out
        - Punch Out Pending: punch in recorded, punch out missing
        - Absent: no punch in and day closed
        """
        if self.date.weekday() == 6:
            return "Holiday"

        if self.punch_in:
            if not self.punch_out:
                return "Punch Out Pending"
            if self.punch_in <= time(9, 35, 0):
                return "Present / On Time"
            else:
                return "Late"

        now_dt = timezone.localtime(timezone.now())
        today = now_dt.date()
        closing_time = time(18, 30, 0)

        if self.date < today:
            return "Absent"
        elif self.date == today:
            if now_dt.time() >= closing_time:
                return "Absent"
            return "Not Marked"
        else:
            return "Scheduled"

    @property
    def status_badge_class(self):
        s = self.status
        if "Present" in s:
            return "badge-present"
        elif "Late" in s:
            return "badge-late"
        elif "Pending" in s:
            return "badge-pending"
        elif "Holiday" in s:
            return "badge-holiday"
        elif "Absent" in s:
            return "badge-absent"
        return "badge-secondary"

    @property
    def row_css_class(self):
        s = self.status
        if "Present" in s:
            return "row-present"
        elif "Late" in s:
            return "row-late"
        elif "Pending" in s:
            return "row-pending"
        elif "Holiday" in s:
            return "row-holiday"
        elif "Absent" in s:
            return "row-absent"
        return ""

    @property
    def formatted_working_hours(self):
        if not self.punch_in or not self.punch_out:
            return "-"
        in_sec = self.punch_in.hour * 3600 + self.punch_in.minute * 60 + self.punch_in.second
        out_sec = self.punch_out.hour * 3600 + self.punch_out.minute * 60 + self.punch_out.second
        diff_sec = max(0, out_sec - in_sec)
        hours = diff_sec // 3600
        mins = (diff_sec % 3600) // 60
        return f"{hours} hrs {mins} mins"

    @property
    def delay_display(self):
        if self.is_late and self.late_minutes > 0:
            return f"{self.late_minutes} min late"
        elif self.punch_in:
            return "On Time"
        return "-"


