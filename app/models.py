# Signal to create UserProfile and EmployeeFaceProfile automatically
@receiver(post_save, sender=settings.AUTH_USER_MODEL)
def create_user_profiles(sender, instance, created, **kwargs):
    UserProfile.objects.get_or_create(user=instance)
    face_prof, _ = EmployeeFaceProfile.objects.get_or_create(user=instance)
    if face_prof.is_enrolled and face_prof.enrollment_status != 'REGISTERED':
        face_prof.enrollment_status = 'REGISTERED'
        face_prof.save(update_fields=['enrollment_status'])